//! `docs/SECURITY.md` "Sandbox": cargo check after the model's edits (#187, `marv-session`'s `diagnostics::cargo`)
//! runs the project's own build scripts and proc macros, so it runs only in the real sandbox: the project read-only,
//! no network, the hidden home hidden, and only its own check cache key folder writable. These run the real cargo in
//! the real sandbox (bubblewrap on Linux, Seatbelt on macOS), and skip only where there's no sandbox or no cargo.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::time::Duration;

use marv_guards::TempDir;
use marv_session::diagnostics::Diagnostic;
use marv_session::diagnostics::cache::{CheckCache, Space, repo_key};
use marv_session::diagnostics::cargo::{Cargo, parse_cargo};
use marv_session::diagnostics::turn::{
    CheckOutcome, CheckRun, Checker, CommandResult, RunCheck, TurnChecks, TurnOptions, sandboxed, sandboxed_options,
};
use tokio_util::sync::CancellationToken;

const GB: u64 = 1024 * 1024 * 1024;

const CARGO_TOML: &str = "[package]\nname = \"marv_guard_fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n";
/// The project is read-only in the check, so cargo can't write a lockfile: a project needs its own (as one with
/// dependencies does to check offline at all).
const CARGO_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"marv_guard_fixture\"\nversion = \"0.1.0\"\n";
const CLEAN: &str = "pub fn answer() -> u32 {\n    42\n}\n";
const BROKEN: &str = "pub fn answer() -> u32 {\n    \"forty-two\"\n}\n";

/// Whether this machine has cargo (the test's own look; Marv never looks on the host).
fn host_has_cargo() -> bool {
    std::process::Command::new("cargo").arg("--version").output().is_ok_and(|o| o.status.success())
}

/// A folder of this test's own where Marv keeps the check cache on this platform (`cache::default_root`), removed
/// when the test ends.
struct HomeCache(PathBuf);

impl HomeCache {
    fn new(tag: &str) -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let home = std::fs::canonicalize(std::env::var("HOME").unwrap()).unwrap();
        let base = if cfg!(target_os = "macos") { home.join("Library/Caches") } else { home.join(".cache") }.join(format!(
            "marv-guard-cargo-{tag}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::SeqCst)
        ));
        std::fs::create_dir_all(&base).unwrap();
        Self(base)
    }

    /// The cache, with the free-space guard answered (a CI runner's disk after a workspace build can be near 5 GB).
    fn cache(&self) -> Arc<CheckCache> {
        let mut cache = CheckCache::new(self.0.join("checks"));
        cache.free_space = Arc::new(|_| Some(Space { available: 100 * GB, total: 200 * GB }));
        Arc::new(cache)
    }
}

impl Drop for HomeCache {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// The real runner, keeping each run and its result.
fn recording(seen: &Arc<Mutex<Vec<(CheckRun, CommandResult)>>>) -> RunCheck {
    let (kept, real) = (seen.clone(), sandboxed());
    Arc::new(move |run: CheckRun, cancel| {
        let (kept, future) = (kept.clone(), real(run.clone(), cancel));
        Box::pin(async move {
            let result = future.await;
            kept.lock().unwrap().push((run, result.clone()));
            result
        })
    })
}

/// The Rust checker on `project`: the real sandbox, the baseline waiting for the warm-up (a cold build on a loaded
/// runner can pass the usual 10 s), and a long timeout.
fn turn(project: &Path, cache: &Arc<CheckCache>, run: RunCheck) -> (TurnChecks, Arc<Mutex<Vec<CheckOutcome<Diagnostic>>>>) {
    let mut checker = Checker::new(Arc::new(Cargo), Some(run));
    checker.cache = Some(cache.clone());
    checker.baseline_wait = Duration::from_secs(600);
    checker.timeout = Duration::from_secs(300);
    let told: Arc<Mutex<Vec<CheckOutcome<Diagnostic>>>> = Default::default();
    let kept = told.clone();
    let checks = Arc::new(checker)
        .turn(TurnOptions {
            root: project.to_path_buf(),
            sandbox: true,
            cancel: CancellationToken::new(),
            on_status: Arc::new(|_| {}),
            on_result: Arc::new(move |r| kept.lock().unwrap().push(r)),
        })
        .expect("a Rust project gets cargo check");
    (checks, told)
}

/// A step that edited `path`.
fn edited(path: &str) -> marv_agent::ToolRun {
    let mut run =
        marv_agent::ToolRun::new(marv_core::ToolResult { output: "Edited".into(), summary: None, is_error: false }, path);
    run.changed = Some(path.into());
    run.display = Some(Arc::new(marv_session::runner::ToolDisplay { diff: Some(Default::default()), plan: None }));
    run
}

/// **cargo check tells an edit's new error once, from its own cache key folder, never the project's `target/`.**
/// Baseline clean, an edit adds E0308 (told), the same again (nothing), the fix (nothing).
///
/// Proven: made `check_command` use the project's `target/` → failed (it can't be made in the read-only project, so
/// the run was unreadable); made `sandboxed_options` drop `project_read_only` or set `network: true` → failed (not
/// the guarded run).
#[tokio::test(flavor = "multi_thread")]
async fn cargo_check_tells_a_new_error_once_and_never_touches_the_projects_target() {
    marv_guards::require_sandbox!();
    if !host_has_cargo() {
        eprintln!("skipped: no cargo here");
        return;
    }
    let home = HomeCache::new("told");
    let cache = home.cache();
    let project = TempDir::new("cargo-check");
    project.write("Cargo.toml", CARGO_TOML);
    project.write("Cargo.lock", CARGO_LOCK);
    project.write("src/lib.rs", CLEAN);
    let seen: Arc<Mutex<Vec<(CheckRun, CommandResult)>>> = Default::default();
    let (checks, told) = turn(project.path(), &cache, recording(&seen));
    checks.before_change.before_change().await;
    let runs = || seen.lock().unwrap().clone();
    assert!(told.lock().unwrap().is_empty(), "{:?} {:?}", told.lock().unwrap(), runs());

    project.write("src/lib.rs", BROKEN);
    let note = (checks.after_step)(vec![edited("src/lib.rs")]).await;
    let note = note.unwrap_or_else(|| panic!("nothing told: {:?} {:?}", told.lock().unwrap(), runs()));
    assert!(note.contains("cargo check found 1 error that wasn't in the previous check."), "{note}");
    assert!(note.contains("src/lib.rs:2:5 E0308 mismatched types: expected `u32`, found `&str`"), "{note}");
    assert_eq!((checks.after_step)(vec![edited("src/lib.rs")]).await, None, "told twice");
    project.write("src/lib.rs", CLEAN);
    assert_eq!((checks.after_step)(vec![edited("src/lib.rs")]).await, None, "a fix was told");

    let key_dir = cache.dir(&repo_key(project.path()));
    assert!(!project.path().join("target").exists(), "the project's target/ was made");
    assert!(key_dir.join("target").is_dir(), "the build isn't in the key folder");
    for (run, _) in runs() {
        let options = sandboxed_options(&run);
        assert!(options.sandbox && options.project_read_only && !options.network, "not the guarded run");
        assert_eq!(options.writable, vec![key_dir.clone()]);
    }
}

/// **A malicious `build.rs` runs sandboxed** (#187: cargo check runs the project's build scripts at the session's
/// first edit): it can't write into the project, the real home, the cache root or another project's key folder,
/// can't read a hidden home path, and can't reach the network; and the check still reports the project's error.
///
/// Proven (Linux): made `sandboxed_options` drop `project_read_only` → failed ("project: ALLOWED"); made it mount the
/// key folder's parent → failed (the other key's folder was writable); `network: true` → failed (the connection was
/// made); made `check_command` use the project's `target/` → failed (the build script never ran).
#[tokio::test(flavor = "multi_thread")]
async fn a_malicious_build_script_runs_sandboxed_and_the_check_still_reports() {
    marv_guards::require_sandbox!();
    if !host_has_cargo() {
        eprintln!("skipped: no cargo here");
        return;
    }
    let home_cache = HomeCache::new("hostile");
    let cache = home_cache.cache();
    let other = cache.key_dir("another-project").unwrap();
    let secret = home_cache.0.join("secret");
    std::fs::write(&secret, "HIDDEN-HOME-SECRET\n").unwrap();
    let real_home = std::fs::canonicalize(std::env::var("HOME").unwrap()).unwrap();
    let in_home = real_home.join(format!("marv-guard-planted-{}", std::process::id()));
    let project = TempDir::new("cargo-hostile");
    let targets = [
        ("project", project.path().join("planted.txt")),
        ("home", in_home.clone()),
        ("cache root", cache.root.join("planted")),
        ("other key", other.join("planted")),
    ];
    let writes: String = targets
        .iter()
        .map(|(name, path)| format!("    attempt(&mut report, {name:?}, std::fs::write({:?}, \"pwned\").is_ok());\n", path))
        .collect();
    project.write("Cargo.toml", &format!("{CARGO_TOML}build = \"build.rs\"\n"));
    project.write("Cargo.lock", CARGO_LOCK);
    project.write("src/lib.rs", BROKEN);
    project.write(
        "build.rs",
        &format!(
            r#"use std::time::Duration;
fn attempt(report: &mut String, what: &str, allowed: bool) {{
    report.push_str(&format!("{{what}}: {{}}\n", if allowed {{ "ALLOWED" }} else {{ "denied" }}));
}}
fn main() {{
    let mut report = String::new();
{writes}    attempt(&mut report, "read secret", std::fs::read_to_string({secret:?}).is_ok());
    let addr = "1.1.1.1:80".parse().unwrap();
    attempt(&mut report, "network", std::net::TcpStream::connect_timeout(&addr, Duration::from_secs(3)).is_ok());
    let out = std::env::var("OUT_DIR").unwrap();
    std::fs::write(format!("{{out}}/report.txt"), report).unwrap();
}}
"#
        ),
    );
    let seen: Arc<Mutex<Vec<(CheckRun, CommandResult)>>> = Default::default();
    let (checks, _told) = turn(project.path(), &cache, recording(&seen));
    checks.before_change.before_change().await;
    let runs = seen.lock().unwrap().clone();

    // The build script ran (in the key folder's target dir), and everything it tried was refused.
    let key_dir = cache.dir(&repo_key(project.path()));
    let report = find_report(&key_dir.join("target")).unwrap_or_else(|| panic!("the build script didn't run: {runs:?}"));
    for line in ["project: denied", "other key: denied", "read secret: denied", "network: denied"] {
        assert!(report.lines().any(|l| l == line), "{line:?} not in:\n{report}");
    }
    // The home and the cache root around the key folder are the sandbox's own throwaway stand-ins under bwrap (a
    // write there can succeed inside), refused outright under Seatbelt: either way, nothing reaches the host.
    for (name, path) in &targets {
        assert!(!path.exists(), "the build script wrote {name}: {}", path.display());
    }
    // And the check still reports the project's error.
    let (_, baseline) = runs.last().expect("the baseline ran");
    let errors = parse_cargo(&baseline.output, baseline.exit_code).unwrap_or_else(|| panic!("unreadable: {baseline:?}"));
    assert!(errors.iter().any(|e| e.code == "E0308"), "{errors:?}");
    let _ = std::fs::remove_file(&in_home);
}

/// The build script's report, under `target/debug/build/<pkg>-<hash>/out/`.
fn find_report(target: &Path) -> Option<String> {
    let build = target.join("debug/build");
    std::fs::read_dir(build).ok()?.flatten().find_map(|e| std::fs::read_to_string(e.path().join("out/report.txt")).ok())
}
